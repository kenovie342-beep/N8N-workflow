// Embeds web.html into src/ui-html.js so the Worker can serve the dashboard without any build step on Cloudflare.
import { readFileSync, writeFileSync } from "node:fs";
const html = readFileSync(new URL("./web.html", import.meta.url), "utf8");
writeFileSync(new URL("./src/ui-html.js", import.meta.url), `// GENERATED by build-ui.mjs from web.html - do not edit.\nexport const HTML = ${JSON.stringify(html)};\n`);
console.log("ui-html.js written,", html.length, "bytes");
